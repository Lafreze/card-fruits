"""Package transparent cartoon PNGs. Requires Pillow.
Usage: python3 scripts/package-fruit-art.py output/imagegen/source
Only resize and encode approved artwork; never paint pixels or add shadows.
"""
from pathlib import Path
from io import BytesIO
import hashlib
import json
import re
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
subjects = json.loads((ROOT / 'art/cartoon-fruit-prompts.json').read_text())['subjects']
output = ROOT / 'public/fruit-toons'
output.mkdir(parents=True, exist_ok=True)
urls = []
for subject in subjects:
    slug = subject['slug']
    with Image.open(source / f'{slug}.png') as original:
        rgba = original.convert('RGBA')
        alpha = rgba.getchannel('A')
        if alpha.getextrema() != (0, 255):
            raise ValueError(f'{slug}: expected transparent background and opaque fruit')
        # Normalize transparent padding so all 50 fruits read at card size.
        fruit = rgba.crop(alpha.getbbox())
        fruit.thumbnail((336, 336), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', (384, 384))
        canvas.paste(fruit, ((384-fruit.width)//2, (384-fruit.height)//2))
        encoded = BytesIO()
        canvas.save(encoded, format='WEBP', lossless=True, method=6)
        content = encoded.getvalue()
        digest = hashlib.sha256(content).hexdigest()[:12]
        filename = f'{slug}.{digest}.webp'
        (output / filename).write_bytes(content)
        urls.append(f'/fruit-toons/{filename}')

# Preserve the code-native expansion fruits when repackaging the original set.
urls.extend(json.loads((ROOT / 'art/cartoon-extra-fruits.json').read_text()))

manifest = '// Generated by scripts/package-fruit-art.py. Content hashes prevent stale artwork.\n'
manifest += 'export const FRUIT_ART = ' + json.dumps(urls, indent=2) + ' as const;\n'
(ROOT / 'src/game/fruit-art.ts').write_text(manifest)
index = ROOT / 'index.html'
index.write_text(re.sub(r'<link rel="icon" href="[^"]+" />', f'<link rel="icon" href="{urls[-1]}" />', index.read_text()))
print(f'Packaged {len(urls)} transparent cartoon fruits.')
